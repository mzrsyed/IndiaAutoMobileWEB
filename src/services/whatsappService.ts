import { SaleRecord } from '../types';

export function formatWhatsAppUrlForSale(sale: SaleRecord): string {
  if (!sale || !sale.customer || !sale.customer.contact) return '#';
  let phone = (sale.customer.contact || '').replace(/\D/g, '');
  if (phone.length === 10) {
    phone = '91' + phone;
  }

  let itemsList = '';
  (sale.items || []).forEach((item, index) => {
    const codeText = item.code && item.code !== '-' ? ` [${item.code}]` : '';
    const discText = item.discountPct ? ` (Disc: ${item.discountPct}%)` : '';
    itemsList += `${index + 1}. *${item.name}*${codeText} x${item.qty}${discText} = ₹${(Number(item.total) || 0).toFixed(2)}\n`;
  });

  const dateStr = sale.timestamp ? new Date(sale.timestamp).toLocaleString() : new Date().toLocaleString();
  const message =
`*INDIA AUTOMOBILES - Invoice / Bill*
--------------------------------
👤 *Proprietor:* Khaja Mungle
📞 *Owner Contact:* +91 8055650977
📄 *Invoice ID:* ${sale.id}
📅 *Date:* ${dateStr}
👤 *Customer:* ${sale.customer.name}
📱 *Customer Phone:* ${sale.customer.contact}

*Purchased Items & Codes:*
${itemsList}--------------------------------
💰 *Subtotal:* ₹${(Number(sale.subtotal) || Number(sale.total) || 0).toFixed(2)}
${sale.discountAmount ? `🎁 *Discount:* -₹${Number(sale.discountAmount).toFixed(2)}\n` : ''}💵 *Grand Total:* ₹${(Number(sale.total) || 0).toFixed(2)}
💳 *Payment Mode:* ${sale.paymentMode || 'Cash'}
✅ *Amount Paid:* ₹${(Number(sale.paid) || 0).toFixed(2)}
${Number(sale.balance) > 0 ? `⚠️ *Remaining Balance (Due):* ₹${Number(sale.balance).toFixed(2)}\n` : `✨ *Status:* Fully Paid (₹0.00 Due)\n`}--------------------------------
✍️ *Generated by:* ${sale.generatedBy || 'Admin'}
_Thank you for choosing India Automobiles!_`;

  return `https://wa.me/${phone}?text=${encodeURIComponent(message)}`;
}

export function formatWhatsAppUrlForLedger(
  customerName: string,
  contact: string,
  orders: SaleRecord[]
): string {
  if (!contact) return '#';
  let phone = contact.replace(/\D/g, '');
  if (phone.length === 10) {
    phone = '91' + phone;
  }

  let totalSpent = 0;
  let totalPaid = 0;
  let totalDue = 0;
  (orders || []).forEach(o => {
    totalSpent += Number(o.total) || 0;
    totalPaid += Number(o.paid) || 0;
    totalDue += Number(o.balance) || 0;
  });

  const recentOrdersStr = orders.slice(0, 5).map((o, idx) =>
    `${idx + 1}. *${o.id}* (${new Date(o.timestamp).toLocaleDateString()}) - Total: ₹${o.total.toFixed(2)}, Due: ₹${o.balance.toFixed(2)}`
  ).join('\n');

  const message =
`*INDIA AUTOMOBILES - Customer Account Ledger*
--------------------------------
👤 *Proprietor:* Khaja Mungle (+91 8055650977)
👤 *Customer:* ${customerName}
📱 *Phone:* ${contact}
📅 *Date:* ${new Date().toLocaleDateString()}

📊 *Account Summary:*
🛒 *Total Orders:* ${orders.length}
💰 *Total Purchases:* ₹${totalSpent.toFixed(2)}
✅ *Total Paid:* ₹${totalPaid.toFixed(2)}
${totalDue > 0 ? `⚠️ *Outstanding Balance (Due):* ₹${totalDue.toFixed(2)}\n` : `✨ *Status:* Fully Cleared (₹0 Due)\n`}
*Recent Invoices:*
${recentOrdersStr}
--------------------------------
_Thank you for your business with India Automobiles! For queries, contact Khaja Mungle (8055650977)._`;

  return `https://wa.me/${phone}?text=${encodeURIComponent(message)}`;
}

export function formatWhatsAppUrlForTotalDueReminder(
  customerName: string,
  contact: string,
  orders: SaleRecord[]
): string {
  if (!contact) return '#';
  let phone = contact.replace(/\D/g, '');
  if (phone.length === 10) {
    phone = '91' + phone;
  }

  let totalSpent = 0;
  let totalPaid = 0;
  let totalDue = 0;
  const pendingOrders: SaleRecord[] = [];

  (orders || []).forEach(o => {
    const billTotal = Number(o.total) || 0;
    const billPaid = Number(o.paid) || 0;
    const billBal = Math.max(0, Number((billTotal - billPaid).toFixed(2)));
    totalSpent += billTotal;
    totalPaid += billPaid;
    totalDue += billBal;
    if (billBal > 0.001) {
      pendingOrders.push(o);
    }
  });

  const pendingBillsList = pendingOrders
    .slice(0, 5)
    .map((o, idx) => {
      const bal = Math.max(0, (Number(o.total) || 0) - (Number(o.paid) || 0));
      return `  ${idx + 1}. *Bill #${o.id}* (${new Date(o.timestamp).toLocaleDateString()}) - Bill: ₹${Number(o.total).toFixed(2)} | Due: *₹${bal.toFixed(2)}*`;
    })
    .join('\n');
  const moreBillsNote = pendingOrders.length > 5 ? `\n  ...and ${pendingOrders.length - 5} more pending bill(s)` : '';

  let message = '';
  if (totalDue > 0.001) {
    message =
`*INDIA AUTOMOBILES - TOTAL ACCOUNT DUE REMINDER*
--------------------------------
👤 *Proprietor:* Khaja Mungle
📞 *Owner Contact:* +91 8055650977
👤 *Customer Name:* ${customerName}
📱 *Customer Phone:* ${contact}
📅 *Date:* ${new Date().toLocaleDateString()}

📊 *TOTAL ACCOUNT BILLING SUMMARY:*
🛍️ *Total Orders:* ${orders.length}
💰 *Total Purchases:* ₹${totalSpent.toFixed(2)}
✅ *Total Paid Amount:* ₹${totalPaid.toFixed(2)}
⚠️ *TOTAL OUTSTANDING DUE BALANCE: ₹${totalDue.toFixed(2)}*
--------------------------------
📋 *Pending Bills Overview (${pendingOrders.length}):*
${pendingBillsList}${moreBillsNote}
--------------------------------

Dear ${customerName},
This is a gentle payment reminder from *India Automobiles* regarding your overall pending due balance of *₹${totalDue.toFixed(2)}*.

Kindly arrange to clear this total outstanding amount at your earliest convenience.
💳 *Payment Modes Accepted:* Cash / UPI / PhonePe / GPay / Bank Transfer.

_Thank you for choosing India Automobiles!_
📞 *Contact:* Khaja Mungle (+91 8055650977)`;
  } else {
    message =
`*INDIA AUTOMOBILES - ACCOUNT FULLY SETTLED*
--------------------------------
👤 *Proprietor:* Khaja Mungle (+91 8055650977)
👤 *Customer Name:* ${customerName}
📱 *Customer Phone:* ${contact}
📅 *Date:* ${new Date().toLocaleDateString()}

💰 *Total Purchases:* ₹${totalSpent.toFixed(2)}
✅ *Total Paid:* ₹${totalPaid.toFixed(2)}
✨ *Total Outstanding Balance:* ₹0.00 (Fully Cleared)

_Thank you for clearing your balance and supporting India Automobiles!_`;
  }

  return `https://wa.me/${phone}?text=${encodeURIComponent(message)}`;
}

