/**
 * Share PDF file directly (to WhatsApp / OS share sheet)
 * Uses Web Share API files support. If unsupported or cancelled on desktop,
 * provides seamless fallback to download and WhatsApp chat link.
 */
export async function sharePDFFile(
  file: File,
  title: string,
  text: string
): Promise<{ sharedDirectly: boolean }> {
  try {
    if (typeof navigator !== 'undefined' && typeof navigator.share === 'function') {
      let canShareFiles = false;
      try {
        canShareFiles = !!(navigator.canShare && navigator.canShare({ files: [file] }));
      } catch {
        canShareFiles = false;
      }

      if (canShareFiles) {
        await navigator.share({
          files: [file],
          title,
          text
        });
        return { sharedDirectly: true };
      }
    }
  } catch (err: unknown) {
    if (err instanceof Error && err.name === 'AbortError') {
      // User dismissed native share sheet
      return { sharedDirectly: true };
    }
    console.warn('Native file share failed, falling back to download:', err);
  }

  // Fallback for desktop browsers & iframes without direct file sharing:
  // Trigger file download so user can attach to WhatsApp
  try {
    const url = URL.createObjectURL(file);
    const a = document.createElement('a');
    a.href = url;
    a.download = file.name;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => {
      try {
        URL.revokeObjectURL(url);
      } catch {
        // ignore
      }
    }, 10000);
  } catch (err) {
    console.warn('File download fallback notice:', err);
  }

  return { sharedDirectly: false };
}
