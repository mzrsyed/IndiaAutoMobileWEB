import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { SaleRecord } from '../types';
import { getLogoPngDataUrl } from '../components/Logo';

export async function generateInvoicePDF(sale: SaleRecord): Promise<void> {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const logoImg = await getLogoPngDataUrl();

  // 1. Watermark Background
  if (logoImg && logoImg.startsWith('data:image/png')) {
    try {
      doc.saveGraphicsState();
      const GState = (doc as unknown as { GState?: new (options: { opacity: number }) => unknown }).GState;
      if (GState) {
        doc.setGState(new GState({ opacity: 0.08 }));
      }
      doc.addImage(logoImg, 'PNG', 45, 85, 120, 120, undefined, 'FAST');
      doc.restoreGraphicsState();
    } catch (err) {
      console.warn('Watermark rendering notice:', err);
    }
  }

  // 2. Header with Logo & Brand Text
  if (logoImg && logoImg.startsWith('data:image/png')) {
    try {
      doc.addImage(logoImg, 'PNG', 14, 12, 22, 22, undefined, 'FAST');
    } catch (err) {
      console.warn('Header logo notice:', err);
    }
  }

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(20, 38, 66); // Navy blue brand color
  doc.text('INDIA AUTOMOBILES', 40, 16);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(30, 41, 59);
  doc.text('Address: Near ICICI Bank Main Road Ausa', 40, 22);

  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(70, 70, 70);
  doc.text('Proprietor: Khaja Mungle  |  Contact: +91 8055650977', 40, 27);
  doc.text('Local Inventory & Customer Billing Management System', 40, 32);

  doc.setDrawColor(220, 220, 220);
  doc.line(14, 37, 196, 37);

  // 3. Invoice & Customer Meta
  doc.setFontSize(10);
  doc.setTextColor(0, 0, 0);
  doc.setFont('helvetica', 'bold');
  doc.text(`TAX / RETAIL INVOICE: ${sale.id}`, 14, 44);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(`Customer Name: ${sale.customer.name}`, 14, 50);
  doc.text(`Contact: ${sale.customer.contact}`, 14, 56);

  const saleDate = new Date(sale.timestamp);
  doc.text(`Date: ${saleDate.toLocaleDateString()}`, 130, 44);
  doc.text(`Time: ${saleDate.toLocaleTimeString()}`, 130, 50);
  doc.text(`Payment Mode: ${sale.paymentMode || 'Cash'}`, 130, 56);

  // 4. Line Items Table with Serial Number
  const tableData = sale.items.map((item, idx) => [
    (idx + 1).toString(),
    item.code || '-',
    item.name,
    item.qty.toString(),
    `Rs. ${(Number(item.basePrice) || 0).toFixed(2)}`,
    item.discountPct ? `${item.discountPct}%` : '0%',
    `Rs. ${(Number(item.price) || 0).toFixed(2)}`,
    `Rs. ${(Number(item.total) || 0).toFixed(2)}`
  ]);

  autoTable(doc, {
    startY: 62,
    head: [['Sr.', 'Item Code', 'Item Description / Name', 'Qty', 'MRP/Rate', 'Disc %', 'Net Rate', 'Total (Rs.)']],
    body: tableData,
    theme: 'grid',
    headStyles: { fillColor: [20, 38, 66], textColor: [255, 255, 255], fontStyle: 'bold', halign: 'center' },
    columnStyles: {
      0: { cellWidth: 12, halign: 'center', fontStyle: 'bold' },
      1: { cellWidth: 24, halign: 'center' },
      2: { cellWidth: 54, halign: 'left' },
      3: { cellWidth: 14, halign: 'center', fontStyle: 'bold' },
      4: { cellWidth: 20, halign: 'right' },
      5: { cellWidth: 14, halign: 'center' },
      6: { cellWidth: 20, halign: 'right' },
      7: { cellWidth: 24, halign: 'right', fontStyle: 'bold' }
    },
    styles: { fontSize: 8.5, cellPadding: 2.5 },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    margin: { left: 14, right: 14 }
  });

  const lastTableY = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY || 70;
  let finalY = lastTableY + 8;
  if (finalY > 225) {
    doc.addPage();
    finalY = 20;
  }

  // 5. Total Calculations
  doc.setFont('helvetica', 'normal');
  doc.text(`Subtotal: Rs. ${(sale.subtotal || sale.total).toFixed(2)}`, 130, finalY);
  if (sale.discountAmount) {
    doc.text(`Bill Discount: - Rs. ${sale.discountAmount.toFixed(2)}`, 130, finalY + 6);
  }
  doc.setFont('helvetica', 'bold');
  doc.text(`Grand Total: Rs. ${sale.total.toFixed(2)}`, 130, finalY + (sale.discountAmount ? 12 : 6));
  doc.setFont('helvetica', 'normal');
  doc.text(`Payment Option: ${sale.paymentMode || 'Cash'}`, 130, finalY + (sale.discountAmount ? 18 : 12));
  doc.text(`Paid: Rs. ${sale.paid.toFixed(2)}`, 130, finalY + (sale.discountAmount ? 24 : 18));
  doc.text(`Remaining Balance: Rs. ${sale.balance.toFixed(2)}`, 130, finalY + (sale.discountAmount ? 30 : 24));

  doc.setFontSize(8.5);
  doc.setTextColor(60, 60, 60);
  doc.setFont('helvetica', 'bold');
  doc.text(`Generated by: ${sale.generatedBy || 'Admin'}`, 14, finalY + 34);

  doc.setFontSize(8);
  doc.setTextColor(100, 100, 100);
  doc.setFont('helvetica', 'normal');
  doc.text('India Automobiles  |  Near ICICI Bank Main Road Ausa  |  Khaja Mungle (+91 8055650977)', 14, finalY + 40);

  doc.save(`Invoice_${sale.id}.pdf`);
}

